-- QueueLess — Smart Campus Queue Management System
-- Database Schema Definition (Milestone 1)
--
-- Target Database: MySQL 8.x (InnoDB Storage Engine)
-- Character Set: utf8mb4 / Collation: utf8mb4_unicode_ci
-- ============================================================================

-- Disable foreign key checks during migration table recreation
SET FOREIGN_KEY_CHECKS = 0;

-- ----------------------------------------------------------------------------
-- 1. Table: users
-- Core authentication and identity table supporting role-based access.
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `queue_tickets`;
DROP TABLE IF EXISTS `services`;
DROP TABLE IF EXISTS `users`;

CREATE TABLE `users` (
    `id` INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `name` VARCHAR(100) NOT NULL COMMENT 'Full name of the user',
    `email` VARCHAR(191) NOT NULL COMMENT 'Unique university or personal email address',
    `password_hash` VARCHAR(255) NOT NULL COMMENT 'Bcrypt or Argon2 password hash generated by password_hash()',
    `role` ENUM('student', 'staff', 'admin') NOT NULL DEFAULT 'student' COMMENT 'Access tier within the campus system',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Timestamp when account was created',

    CONSTRAINT `uq_users_email` UNIQUE (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='User identity and authentication records';

-- ----------------------------------------------------------------------------
-- 2. Table: services
-- Campus departments and counters offering virtual queue access.
-- ----------------------------------------------------------------------------
CREATE TABLE `services` (
    `id` INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `name` VARCHAR(100) NOT NULL COMMENT 'Unique title of the campus service or department counter',
    `description` TEXT NULL COMMENT 'Descriptive details of services rendered and requirements',
    `staff_id` INT UNSIGNED NULL COMMENT 'Assigned staff operator (1:1 relationship)',
    `is_open` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 = accepting new queue tickets, 0 = temporarily closed',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Timestamp when service counter was registered',

    CONSTRAINT `uq_services_name` UNIQUE (`name`),
    
    -- 1:1 cardinality constraint: At most one service per staff member,
    -- and at most one staff member per service (NULL indicates currently unassigned).
    CONSTRAINT `uq_services_staff_id` UNIQUE (`staff_id`),

    -- Deletion policy: If a staff user account is removed, preserve the campus service
    -- and set staff_id to NULL so service operations and ticket logs are never destroyed.
    CONSTRAINT `fk_services_staff` FOREIGN KEY (`staff_id`)
        REFERENCES `users` (`id`)
        ON DELETE SET NULL
        ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Campus service counters and availability';

-- ----------------------------------------------------------------------------
-- 3. Table: queue_tickets
-- Virtual queue tokens issued to students for specific campus services.
-- ----------------------------------------------------------------------------
CREATE TABLE `queue_tickets` (
    `id` INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `student_id` INT UNSIGNED NOT NULL COMMENT 'Foreign key to users(id)',
    `service_id` INT UNSIGNED NOT NULL COMMENT 'Foreign key to services(id)',
    `token_number` INT UNSIGNED NOT NULL COMMENT 'Sequential token identifier within this service',
    `status` ENUM('waiting', 'serving', 'served', 'completed', 'cancelled', 'skipped') NOT NULL DEFAULT 'waiting' COMMENT 'Queue lifecycle status',
    `active_student_id` INT UNSIGNED GENERATED ALWAYS AS (
        CASE
            WHEN `status` IN ('waiting', 'serving') THEN `student_id`
            ELSE NULL
        END
    ) STORED COMMENT 'Generated safeguard: non-NULL only while ticket is active',
    `joined_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Timestamp when student entered the virtual queue',
    `called_at` DATETIME NULL DEFAULT NULL COMMENT 'Timestamp when staff operator summoned the ticket',
    `finished_at` DATETIME NULL DEFAULT NULL COMMENT 'Timestamp when service was completed or closed',

    -- Composite unique constraint: Prevents duplicate token numbers from ever existing
    -- within the same service counter.
    CONSTRAINT `uq_service_token` UNIQUE (`service_id`, `token_number`),

    -- Final database safeguard for the single active ticket policy.
    -- MySQL permits multiple NULL values in a UNIQUE key, so terminal tickets
    -- remain unlimited while waiting/serving tickets are limited to one per student.
    CONSTRAINT `uq_active_ticket_per_student` UNIQUE (`active_student_id`),

    -- Deletion policies: ON DELETE RESTRICT guarantees strict historical audit preservation.
    -- Neither user accounts nor service counters can be silently dropped while ticket history exists.
    CONSTRAINT `fk_tickets_student` FOREIGN KEY (`student_id`)
        REFERENCES `users` (`id`)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT `fk_tickets_service` FOREIGN KEY (`service_id`)
        REFERENCES `services` (`id`)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    -- Performance indexes for frequent dashboard lookups
    INDEX `idx_tickets_student_status` (`student_id`, `status`),
    INDEX `idx_tickets_service_status` (`service_id`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Virtual queue tickets and service lifecycle';

-- Re-enable foreign key constraints
SET FOREIGN_KEY_CHECKS = 1;

-- ============================================================================
-- ARCHITECTURAL NOTES & BUSINESS RULES (For Reference and Academic Defense):
--
-- 1. Single Active Ticket Policy (System-Wide):
--    A student may hold at most ONE active ticket ('waiting' or 'serving')
--    across all campus services simultaneously.
--    * Why: A student cannot be in two places at once. Allowing multiple active
--      tickets creates ghost queues, false wait estimates, and no-shows when
--      two counters summon the student concurrently.
--    * Why a simple database UNIQUE constraint on (student_id, status) CANNOT be used:
--      A student returns to campus services on multiple days. Once tickets reach
--      a terminal status ('served', 'completed', 'cancelled'), multiple terminal
--      records accumulate. MySQL 8.x lacks partial/filtered unique indexes.
--    * Implementation Solution:
--      Enforced by two layers:
--      (a) Application transaction locks the student's users row before checking tickets.
--      (b) Generated column active_student_id plus UNIQUE constraint provides the
--          final database safeguard.
--      Inside the transaction:
--      SELECT id FROM users WHERE id = ? AND role = 'student' FOR UPDATE;
--      SELECT id, service_id FROM queue_tickets
--      WHERE student_id = ? AND status IN ('waiting', 'serving')
--      FOR UPDATE;
--      If a row exists, subsequent join requests are rejected with a clear notice.
--
-- 2. Safe Token Allocation Under High Concurrency:
--    Under concurrent student requests, a naive `SELECT MAX(token_number) + 1`
--    causes race conditions and collision errors against `uq_service_token`.
--    * Implementation Solution:
--      Enclose token assignment in a strict InnoDB transaction using pessimistic
--      locking on the service record:
--      START TRANSACTION;
--      SELECT id FROM services WHERE id = ? FOR UPDATE;
--      SELECT COALESCE(MAX(token_number), 0) + 1 INTO @next_token FROM queue_tickets WHERE service_id = ?;
--      INSERT INTO queue_tickets (student_id, service_id, token_number, status, joined_at)
--      VALUES (?, ?, @next_token, 'waiting', NOW());
